/* Lua and Python scripts could not read the constants of libobs/obs-defs.h
 * (obsproject/obs-studio#8936, reported by Smartkin): obs.OBS_ALIGN_LEFT was
 * nil in Lua and missing in Python, as were the other alignment flags and
 * the MODULE_*, OBS_OUTPUT_* and OBS_VIDEO_* return codes, so scripts had to
 * define the values themselves. obs.h includes obs-defs.h, but SWIG does not
 * follow #include, and obslua.i and obspython.i never %include obs-defs.h.
 *
 * The build generates the Lua and Python wrappers from the real obslua.i and
 * obspython.i and links them into this test. Each case runs a script that
 * loads the module the way OBS scripts do (require "obslua" / import
 * obspython), reports every obs-defs.h constant and OBS_ALIGN_LEFT |
 * OBS_ALIGN_TOP, and the test compares them with the C values. LOG_WARNING,
 * which the modules already export, checks the harness itself. No obs core
 * and no display are needed. */

#define PY_SSIZE_T_CLEAN
#include <Python.h>

#include <stdarg.h>
#include <stddef.h>
#include <setjmp.h>
#include <cmocka.h>

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <lua.h>
#include <lauxlib.h>
#include <lualib.h>

#include <obs.h>
#include <util/base.h>
#include <util/dstr.h>

/* Generated by SWIG from obslua.i and obspython.i. */
extern int luaopen_obslua(lua_State *L);
extern PyObject *PyInit__obspython(void);

struct obs_def {
	const char *name;
	long long value;
};

#define DEF(x) {#x, (x)}

static const struct obs_def obs_defs[] = {
	DEF(LOG_WARNING), /* already exported: checks the harness */
	DEF(MAX_CHANNELS),
	DEF(OBS_ALIGN_CENTER),
	DEF(OBS_ALIGN_LEFT),
	DEF(OBS_ALIGN_RIGHT),
	DEF(OBS_ALIGN_TOP),
	DEF(OBS_ALIGN_BOTTOM),
	DEF(MODULE_SUCCESS),
	DEF(MODULE_ERROR),
	DEF(MODULE_FAILED_TO_OPEN),
	DEF(MODULE_FILE_NOT_FOUND),
	DEF(MODULE_MISSING_EXPORTS),
	DEF(MODULE_INCOMPATIBLE_VER),
	DEF(MODULE_HARDCODED_SKIP),
	DEF(OBS_OUTPUT_SUCCESS),
	DEF(OBS_OUTPUT_BAD_PATH),
	DEF(OBS_OUTPUT_CONNECT_FAILED),
	DEF(OBS_OUTPUT_INVALID_STREAM),
	DEF(OBS_OUTPUT_ERROR),
	DEF(OBS_OUTPUT_DISCONNECTED),
	DEF(OBS_OUTPUT_UNSUPPORTED),
	DEF(OBS_OUTPUT_NO_SPACE),
	DEF(OBS_OUTPUT_ENCODE_ERROR),
	DEF(OBS_OUTPUT_HDR_DISABLED),
	DEF(OBS_VIDEO_SUCCESS),
	DEF(OBS_VIDEO_FAIL),
	DEF(OBS_VIDEO_NOT_SUPPORTED),
	DEF(OBS_VIDEO_INVALID_PARAM),
	DEF(OBS_VIDEO_CURRENTLY_ACTIVE),
	DEF(OBS_VIDEO_MODULE_NOT_FOUND),
	{"OBS_ALIGN_LEFT|OBS_ALIGN_TOP", OBS_ALIGN_LEFT | OBS_ALIGN_TOP},
};

#define NUM_DEFS (sizeof(obs_defs) / sizeof(obs_defs[0]))

/* The scripts report one "NAME=value" line per constant. */
static void check_report(const char *language, const char *report)
{
	struct dstr text = {0};
	struct dstr key = {0};
	int wrong = 0;

	dstr_printf(&text, "\n%s", report);
	for (size_t i = 0; i < NUM_DEFS; i++) {
		dstr_printf(&key, "\n%s=", obs_defs[i].name);
		const char *found = strstr(text.array, key.array);
		const char *value = found ? found + key.len : "(not reported)\n";
		long long expected = obs_defs[i].value;
		char *end = NULL;
		long long got = found ? strtoll(value, &end, 10) : 0;

		if (!found || end == value || *end != '\n' || got != expected) {
			fprintf(stderr, "%s: %s is %.*s, expected %lld\n", language, obs_defs[i].name,
				(int)strcspn(value, "\n"), value, expected);
			wrong++;
		}
	}

	if (wrong)
		fprintf(stderr, "%s: %d of %d constants wrong\n", language, wrong, (int)NUM_DEFS);
	dstr_free(&key);
	dstr_free(&text);
	if (wrong)
		fail();
}

static const char *lua_script =
	"local obs = require(\"obslua\")\n"
	"local out = {}\n"
	"for _, name in ipairs(names) do\n"
	"    out[#out + 1] = name .. \"=\" .. tostring(obs[name])\n"
	"end\n"
	"local ok, v = pcall(function()\n"
	"    return bit.bor(obs.OBS_ALIGN_LEFT, obs.OBS_ALIGN_TOP)\n"
	"end)\n"
	"out[#out + 1] = \"OBS_ALIGN_LEFT|OBS_ALIGN_TOP=\" .. (ok and tostring(v) or \"error\")\n"
	"return table.concat(out, \"\\n\") .. \"\\n\"\n";

static void lua_script_reads_obs_defs(void **state)
{
	(void)state;

	lua_State *L = luaL_newstate();
	assert_non_null(L);
	luaL_openlibs(L);

	/* require "obslua" finds the module linked into the test */
	lua_getglobal(L, "package");
	lua_getfield(L, -1, "preload");
	lua_pushcfunction(L, luaopen_obslua);
	lua_setfield(L, -2, "obslua");
	lua_pop(L, 2);

	lua_newtable(L);
	for (size_t i = 0; i + 1 < NUM_DEFS; i++) {
		lua_pushstring(L, obs_defs[i].name);
		lua_rawseti(L, -2, (int)i + 1);
	}
	lua_setglobal(L, "names");

	if (luaL_dostring(L, lua_script) != 0) {
		fprintf(stderr, "the Lua script failed: %s\n", lua_tostring(L, -1));
		lua_close(L);
		fail();
	}

	struct dstr report = {0};
	dstr_copy(&report, lua_tostring(L, -1));
	lua_close(L);

	check_report("Lua", report.array ? report.array : "");
	dstr_free(&report);
}

static const char *python_script = "import obspython as obs\n"
				   "out = ''.join('%s=%s\\n' % (n, getattr(obs, n, None)) for n in names)\n"
				   "try:\n"
				   "    v = obs.OBS_ALIGN_LEFT | obs.OBS_ALIGN_TOP\n"
				   "except Exception as e:\n"
				   "    v = type(e).__name__\n"
				   "out += 'OBS_ALIGN_LEFT|OBS_ALIGN_TOP=%s\\n' % v\n";

static void python_script_reads_obs_defs(void **state)
{
	(void)state;

	/* import obspython loads the generated obspython.py, which imports the
	 * _obspython wrapper linked into the test */
	assert_int_not_equal(PyImport_AppendInittab("_obspython", PyInit__obspython), -1);
	Py_Initialize();
	assert_true(Py_IsInitialized());

	struct dstr prelude = {0};
	dstr_copy(&prelude, "import sys\nsys.path.insert(0, '" OBSPYTHON_DIR "')\nnames = [");
	for (size_t i = 0; i + 1 < NUM_DEFS; i++)
		dstr_catf(&prelude, "'%s', ", obs_defs[i].name);
	dstr_cat(&prelude, "]\n");
	int prelude_ok = PyRun_SimpleString(prelude.array) == 0;
	dstr_free(&prelude);

	int script_ok = prelude_ok && PyRun_SimpleString(python_script) == 0;

	struct dstr report = {0};
	PyObject *out = script_ok ? PyObject_GetAttrString(PyImport_AddModule("__main__"), "out") : NULL;
	if (out && PyUnicode_Check(out))
		dstr_copy(&report, PyUnicode_AsUTF8(out));
	Py_XDECREF(out);
	Py_Finalize();

	if (!script_ok) {
		/* PyRun_SimpleString printed the traceback */
		fprintf(stderr, "the Python script failed\n");
		fail();
	}

	check_report("Python", report.array ? report.array : "");
	dstr_free(&report);
}

int main(void)
{
	const struct CMUnitTest tests[] = {
		cmocka_unit_test(lua_script_reads_obs_defs),
		cmocka_unit_test(python_script_reads_obs_defs),
	};
	return cmocka_run_group_tests(tests, NULL, NULL);
}
