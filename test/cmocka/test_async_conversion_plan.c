static void fill(int format, bool full_range, int trc, uint32_t width, uint32_t height,
		 struct obs_source_conversion_plan *plan)
{
	/* not zero, so a field the function leaves alone shows */
	memset(plan, 0xA5, sizeof(*plan));
	obs_source_conversion_plan_fill(format, full_range, trc, width, height, plan);
}

