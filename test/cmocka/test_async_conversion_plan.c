/*
 * Characterization of the async video GPU conversion plan of obs-source.c,
 * moved to libobs/obs-source-conversion-plan.c before its Rust port:
 * get_convert_type(), the set_*_sizes() of init_gpu_conversion(),
 * select_conversion_technique() and need_linear_output(), through the one
 * hidden function, obs_source_conversion_plan_fill().
 *
 * The whole table is pinned: every enum video_format and two values outside
 * it, both ranges, every enum video_trc, one value outside it (4) and one
 * that wraps to PQ in the frame's uint8_t field (258), at the sizes below.
 * conversion_table holds what the plan gives for each format, range and
 * transfer; size_table holds the plane sizes of each convert type. Both were
 * generated from the moved C at the characterization commit: build this file
 * with -DCONVERSION_PLAN_GENERATE (and the moved file, as the test target
 * does) and run it. The full_table test checks every row against every size.
 * The other cases spell out the rules the tables hold.
 *
 * Frame sizes and formats come from plugins, capture devices and decoded
 * media, so any value can arrive. Characterized, not endorsed: the size
 * rules wrap in uint32_t near UINT32_MAX ((width + 1) / 2 is 0 at
 * UINT32_MAX, width * 3 wraps from 0x55555556 on, (width + 5) / 6 * 4 is 0
 * from UINT32_MAX - 4 on).
 *
 * The functions are hidden in libobs, so this test compiles the C source
 * into itself and calls only obs_source_conversion_plan_fill().
 * test_media_restart_first_frame, test_deinterlace_2x_field_order and
 * test_pipewire_camera_nv12 cover the caller through the real libobs.
 */

