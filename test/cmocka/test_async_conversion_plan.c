static void check_plan(const struct obs_source_conversion_plan *plan, const struct conversion_row *row,
		       const struct size_row *size, const char *where)
{
	if (plan->convert_type != row->convert_type || plan->channel_count != row->channel_count ||
	    plan->linear != row->linear) {
		fprintf(stderr, "%s: convert type %d, %d planes, linear %d (expected %d, %d, %d)\n", where,
			plan->convert_type, plan->channel_count, plan->linear, row->convert_type, row->channel_count,
			row->linear);
		fail();
	}
	for (int c = 0; c < PLANES; c++) {
		if (plan->format[c] != row->plane_format[c] || plan->width[c] != size->width[c] ||
		    plan->height[c] != size->height[c]) {
			fprintf(stderr,
				"%s: plane %d is %" PRIu32 " x %" PRIu32 " format %d (expected %" PRIu32 " x %" PRIu32
				" format %d)\n",
				where, c, plan->width[c], plan->height[c], plan->format[c], size->width[c],
				size->height[c], row->plane_format[c]);
			fail();
		}
	}
	if ((plan->technique == NULL) != (row->technique == NULL) ||
	    (plan->technique && strcmp(plan->technique, row->technique) != 0)) {
		fprintf(stderr, "%s: technique %s (expected %s)\n", where, plan->technique ? plan->technique : "NULL",
			row->technique ? row->technique : "NULL");
		fail();
	}
}

/* The tables cover formats x ranges x transfers in order. */
static void table_covers_every_input(void **state)
{
	(void)state;
	assert_int_equal(COUNT(conversion_table), NUM_FORMATS * 2 * NUM_TRCS);
	size_t i = 0;
	for (size_t f = 0; f < NUM_FORMATS; f++) {
		for (int r = 0; r < 2; r++) {
			for (size_t t = 0; t < NUM_TRCS; t++, i++) {
				assert_int_equal(conversion_table[i].format, formats[f]);
				assert_int_equal(conversion_table[i].full_range, r != 0);
				assert_int_equal(conversion_table[i].trc, trcs[t]);
			}
		}
	}
}

/* Every row at every size: 336 inputs x 14 sizes. */
static void full_table(void **state)
{
	(void)state;
	for (size_t i = 0; i < COUNT(conversion_table); i++) {
		const struct conversion_row *row = &conversion_table[i];
		for (size_t s = 0; s < NUM_SIZES; s++) {
			struct obs_source_conversion_plan plan;
			char where[128];
			snprintf(where, sizeof(where), "format %d range %d trc %d size %" PRIu32 " x %" PRIu32,
				 row->format, row->full_range, row->trc, sizes[s].width, sizes[s].height);
			fill(row->format, row->full_range, row->trc, sizes[s].width, sizes[s].height, &plan);
			check_plan(&plan, row, &size_table[row->convert_type][s], where);
		}
	}
}

/* The planes past channel_count, and every plane of a frame that needs no
 * conversion, are zero (GS_UNKNOWN), whatever the plan held before. */
static void unused_planes_zero(void **state)
{
	(void)state;
	for (size_t i = 0; i < COUNT(conversion_table); i++) {
		const struct conversion_row *row = &conversion_table[i];
		struct obs_source_conversion_plan plan;
		fill(row->format, row->full_range, row->trc, 1920, 1080, &plan);
		for (int c = plan.channel_count; c < PLANES; c++) {
			assert_int_equal(plan.width[c], 0);
			assert_int_equal(plan.height[c], 0);
			assert_int_equal(plan.format[c], GS_UNKNOWN);
		}
		if (plan.convert_type == OBS_SOURCE_CONVERT_NONE)
			assert_int_equal(plan.channel_count, 0);
		else if (plan.channel_count < 1 || plan.channel_count > PLANES) {
			fprintf(stderr, "format %d: %d planes\n", row->format, plan.channel_count);
			fail();
		}
	}
}

