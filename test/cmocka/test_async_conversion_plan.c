static const char *lookup(const struct name *names, size_t count, int value)
{
	static char buf[32];
	for (size_t i = 0; i < count; i++) {
		if (names[i].value == value)
			return names[i].name;
	}
	snprintf(buf, sizeof(buf), "%d", value);
	return buf;
}

static const char *size_literal(uint32_t v, char *buf, size_t len)
{
	if (v >= UINT32_MAX - 5)
		snprintf(buf, len, v == UINT32_MAX ? "UINT32_MAX" : "UINT32_MAX - %u", UINT32_MAX - v);
	else
		snprintf(buf, len, "%" PRIu32 "u", v);
	return buf;
}

int main(void)
{
	printf("static const struct conversion_row conversion_table[] = {\n");
	for (size_t f = 0; f < NUM_FORMATS; f++) {
		for (int r = 0; r < 2; r++) {
			for (size_t t = 0; t < NUM_TRCS; t++) {
				struct obs_source_conversion_plan p;
				fill(formats[f], r != 0, trcs[t], 1920, 1080, &p);
				printf("\t{%s, %s, %s, OBS_SOURCE_CONVERT_%s, %d, {",
				       lookup(format_names, COUNT(format_names), formats[f]), r ? "true" : "false",
				       lookup(trc_names, COUNT(trc_names), trcs[t]), convert_names[p.convert_type],
				       p.channel_count);
				for (int c = 0; c < PLANES; c++)
					printf("%s%s", c ? ", " : "", lookup(gs_names, COUNT(gs_names), p.format[c]));
				if (p.technique)
					printf("}, \"%s\", %s},\n", p.technique, p.linear ? "true" : "false");
				else
					printf("}, NULL, %s},\n", p.linear ? "true" : "false");
			}
		}
	}
	printf("};\n\n");

	/* the sizes depend on the convert type alone: take the first row of
	 * each type, and stop if another row of the type disagrees */
	struct obs_source_conversion_plan first[NUM_CONVERT_TYPES][NUM_SIZES];
	bool seen[NUM_CONVERT_TYPES] = {0};
	for (size_t f = 0; f < NUM_FORMATS; f++) {
		for (int r = 0; r < 2; r++) {
			for (size_t t = 0; t < NUM_TRCS; t++) {
				for (size_t s = 0; s < NUM_SIZES; s++) {
					struct obs_source_conversion_plan p;
					fill(formats[f], r != 0, trcs[t], sizes[s].width, sizes[s].height, &p);
					int type = p.convert_type;
					if (!seen[type] && s == 0) {
						seen[type] = true;
						for (size_t z = 0; z < NUM_SIZES; z++)
							fill(formats[f], r != 0, trcs[t], sizes[z].width,
							     sizes[z].height, &first[type][z]);
					}
					if (memcmp(p.width, first[type][s].width, sizeof(p.width)) != 0 ||
					    memcmp(p.height, first[type][s].height, sizeof(p.height)) != 0) {
						fprintf(stderr, "sizes differ within a convert type\n");
						return 1;
					}
				}
			}
		}
	}

	printf("static const struct size_row size_table[NUM_CONVERT_TYPES][NUM_SIZES] = {\n");
	for (int type = 0; type < NUM_CONVERT_TYPES; type++) {
		printf("\t/* OBS_SOURCE_CONVERT_%s */\n\t{\n", convert_names[type]);
		for (size_t s = 0; s < NUM_SIZES; s++) {
			char a[32], b[32], c[32], d[32], e[32], f[32], g[32], h[32];
			const struct obs_source_conversion_plan *p = &first[type][s];
			printf("\t\t{{%s, %s, %s, %s}, {%s, %s, %s, %s}},\n", size_literal(p->width[0], a, 32),
			       size_literal(p->width[1], b, 32), size_literal(p->width[2], c, 32),
			       size_literal(p->width[3], d, 32), size_literal(p->height[0], e, 32),
			       size_literal(p->height[1], f, 32), size_literal(p->height[2], g, 32),
			       size_literal(p->height[3], h, 32));
		}
		printf("\t},\n");
	}
	printf("};\n");
	return 0;
}

