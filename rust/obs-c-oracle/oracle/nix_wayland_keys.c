/* The values the C uses, in the order of
 * rust/obs-c-oracle/src/nix_wayland_keys.rs. */
enum {
	ORACLE_WAYLAND_KEYS_VALUE_COUNT = 5,
	ORACLE_WAYLAND_KEYS_KEYSYM_COUNT = 334,
};

int64_t oracle_wayland_keys_value(size_t which);
int64_t oracle_wayland_keys_keysym(size_t which);
int oracle_wayland_keys_real_keysyms(void);

int64_t oracle_wayland_keys_value(size_t which)
{
	const int64_t values[ORACLE_WAYLAND_KEYS_VALUE_COUNT] = {
		OBS_KEY_LAST_VALUE,
		OBS_KEY_NONE,
		OBS_NIX_WAYLAND_KEYS_MAX_KEYCODES,
		OBS_NIX_WAYLAND_KEYS_MAX_SHIFT_LEVELS,
		sizeof(obs_key_t),
	};
	return which < ORACLE_WAYLAND_KEYS_VALUE_COUNT ? values[which] : -1;
}

