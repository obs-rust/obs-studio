/// `load_keymap_data()`'s rule for one keycode: nothing for a keycode at or
/// above [`MAX_KEYCODES`]; else for each of the [`MAX_SHIFT_LEVELS`] levels,
/// `level_sym(level)` is its first keysym when it has at least one, which is
/// stored in `key_to_sym[level][keycode]`, and `keycode` in `obs_to_key` at
/// that keysym's key unless one is stored there (0 is none).
pub fn keymap_row(
    keycode: u32,
    mut level_sym: impl FnMut(u32) -> Option<u32>,
    obs_to_key: &mut [u32],
    key_to_sym: &mut [[u32; MAX_KEYCODES]],
) {
    let Some(code) = keycode_index(keycode) else {
        return;
    };
    for level in 0..MAX_SHIFT_LEVELS {
        let Some(sym) = level_sym(u32::try_from(level).unwrap_or(u32::MAX)) else {
            continue;
        };
        let key = from_keysym(i32::from_ne_bytes(sym.to_ne_bytes()));
        // This avoids ambiguity where multiple scancodes produce the same
        // symbols, e.g. LSGT and Shift+AB08 produce `<` on the US layout.
        if let Some(slot) = usize::try_from(key)
            .ok()
            .and_then(|k| obs_to_key.get_mut(k))
            && *slot == 0
        {
            *slot = keycode;
        }
        if let Some(slot) = key_to_sym.get_mut(level).and_then(|row| row.get_mut(code)) {
            *slot = sym;
        }
    }
}

/// `set_focused_key()`'s rule for a focused key event of evdev scancode
/// `scancode` (a press when `pressed`): the key the hotkey state is told
/// about, or `None`.
///
/// Its keycode is `scancode + 8` (wrapping as a `u32`), none at or above
/// [`MAX_KEYCODES`]. A press reports the key of the keycode's level-0 keysym
/// in `key_to_sym0` (none for keysym 0) and records it in
/// `pressed_as[keycode]`; a release reports the key recorded for it, and
/// clears it, or nothing when none is recorded (`OBS_KEY_NONE`).
///
/// Intentional difference from C, which looks a release up again: a key
/// released after a layout change is released as the key it was pressed
/// as, not as what the new layout puts on its keycode.
pub fn focused(
    scancode: u32,
    pressed: bool,
    key_to_sym0: &[u32],
    pressed_as: &mut [i32],
) -> Option<i32> {
    // evdev scancode to XKB keycode
    let code = keycode_index(scancode.wrapping_add(8))?;
    if !pressed {
        let slot = pressed_as.get_mut(code)?;
        let key = std::mem::replace(slot, KEY_NONE);
        return (key != KEY_NONE).then_some(key);
    }
    let sym = *key_to_sym0.get(code)?;
    if sym == 0 {
        return None;
    }
    let key = from_keysym(i32::from_ne_bytes(sym.to_ne_bytes()));
    if let Some(slot) = pressed_as.get_mut(code) {
        *slot = key;
    }
    Some(key)
}

/// `keycode` as an index, for a keycode below [`MAX_KEYCODES`].
fn keycode_index(keycode: u32) -> Option<usize> {
    usize::try_from(keycode)
        .ok()
        .filter(|&code| code < MAX_KEYCODES)
}
