#!/usr/bin/env -S uv run --script
"""Resolve the Tier 2 package list to exact versions and report drift.

`apt-packages.txt` names packages, not versions, so the same image tag can be
rebuilt into different content as `-updates` and `-security` move. That is
wrong for a tag the workflow calls a content identity, and it also means a
stale archive can silently 404 a superseded `.deb` (#5497).

This module keeps a resolved lock (`apt-versions.txt`) beside the list. A
scheduled job regenerates it and opens a pull request when it moves, which is
the only moment a human has to look: a version bump that breaks the build is
cheap to see in a PR and expensive to discover inside a red merge queue.

Commands:
    resolve   print the resolved lock for the current archive
    check     compare the archive against the committed lock; exit 1 on drift

`parse_installs` and `changed` are pure so the interesting half is testable
without an apt environment.
"""
from __future__ import annotations

import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ROOT / 'rust' / 'tools' / 'linux-validate' / 'apt-packages.txt'
LOCK = ROOT / 'rust' / 'tools' / 'linux-validate' / 'apt-versions.txt'
HEADER = ('# Generated by ci/apt_updates.py resolve from apt-packages.txt; do not '
          'edit by hand. A scheduled job refreshes this and opens a pull request.')
INSTALLED = re.compile(r'^Inst (\S+) \((\S+) ', re.M)


def selected_packages(path: Path = PACKAGES) -> list[str]:
    """The package names the list asks for, comments and blanks removed."""
    names = []
    for line in path.read_text().splitlines():
        name = line.split('#', 1)[0].strip()
        if name:
            names.append(name)
    return names


def parse_installs(simulation: str) -> dict[str, str]:
    """Version per package from `apt-get -s --reinstall install` output.

    `-s` prints one `Inst <name> (<version> <origin> [arch])` line per package
    the install would touch; `--reinstall` makes it print the ones already
    present too, so a runner's preinstalled git or curl still lands in the lock.
    """
    return {name: version for name, version in INSTALLED.findall(simulation)}


def parse_lock(text: str) -> dict[str, str]:
    versions = {}
    for line in text.splitlines():
        entry = line.split('#', 1)[0].strip()
        if not entry:
            continue
        name, _, version = entry.partition('=')
        if not name or not version:
            raise ValueError(f'lock line is not name=version: {line!r}')
        versions[name.strip()] = version.strip()
    return versions


def render_lock(versions: dict[str, str]) -> str:
    return HEADER + '\n' + ''.join(f'{name}={versions[name]}\n' for name in sorted(versions))


def changed(old: dict[str, str], new: dict[str, str]) -> list[str]:
    """Human lines describing how the lock moved, sorted by package name."""
    lines = []
    for name in sorted(set(old) | set(new)):
        if name not in new:
            lines.append(f'removed {name}={old[name]}')
        elif name not in old:
            lines.append(f'added {name}={new[name]}')
        elif old[name] != new[name]:
            lines.append(f'changed {name}: {old[name]} -> {new[name]}')
    return lines


def simulate(packages: list[str]) -> str:
    command = ['apt-get', '--reinstall', '-s', 'install', '-y', '--no-install-recommends', *packages]
    if os.geteuid() != 0:
        command.insert(0, 'sudo')
    return subprocess.run(command, capture_output=True, text=True, check=True).stdout


def read_lock() -> dict[str, str]:
    return parse_lock(LOCK.read_text()) if LOCK.is_file() else {}


def main() -> None:
    stage = sys.argv[1] if len(sys.argv) > 1 else 'check'
    resolved = parse_installs(simulate(selected_packages()))
    if not resolved:
        raise SystemExit('apt simulated no installs; is the package list reachable?')
    if stage == 'resolve':
        print(render_lock(resolved), end='')
        return
    if stage != 'check':
        raise SystemExit(f'unknown stage {stage}; expected resolve or check')
    drift = changed(read_lock(), resolved)
    for line in drift:
        print(line)
    print(f'{len(resolved)} packages resolved, {len(drift)} differences')
    sys.exit(1 if drift else 0)


if __name__ == '__main__':
    main()
