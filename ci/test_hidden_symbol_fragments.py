#!/usr/bin/env -S uv run --script
"""libobs's hidden-symbol inventory is one fragment per Rust FFI module (#3233).

A port hides its non-EXPORT shims in its own
`libobs/cmake/rust-hidden.d/<crate>-<ffi module>.txt`, never in a list every
other port edits. `libobs/cmake/rust-hidden.cmake` generates the ELF version
script and the ld64 unexports list from the fragments plus
`rust-hidden-base.txt` at configure time, so neither is committed. A fragment
holds plain names only, Windows reads none of them and Linux's export_list
test checks every name is a shim, so a fragment edit selects Linux only
(#2288 for the earlier, mirrored-lists rule).

    uv run --no-project ci/test_hidden_symbol_fragments.py
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from ci_scope import scope

ROOT = Path(__file__).resolve().parent.parent
CMAKE_DIR = ROOT / "libobs/cmake"
FRAGMENTS = CMAKE_DIR / "rust-hidden.d"
BASE = CMAKE_DIR / "rust-hidden-base.txt"
GENERATOR = CMAKE_DIR / "rust-hidden.cmake"
NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
HEVC = ("obs_hevc_keyframe", "obs_parse_hevc_packet", "obs_parse_hevc_packet_priority", "obs_extract_hevc_headers")


def entries(path: Path) -> list[str]:
    return [s for s in (l.strip() for l in path.read_text().splitlines()) if s and not s.startswith("#")]


def generate(out: Path, fragments: Path = FRAGMENTS, base: Path = BASE, hevc: bool = True) -> tuple[str, str]:
    subprocess.run(
        [
            "cmake",
            f"-DOBS_RUST_HIDDEN_DIR={fragments}",
            f"-DOBS_RUST_HIDDEN_BASE={base}",
            f"-DOBS_RUST_HIDDEN_OUT={out}",
            f"-DOBS_RUST_HIDDEN_HEVC={'ON' if hevc else 'OFF'}",
            "-P",
            str(GENERATOR),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    return (out / "rust-exports.map").read_text(), (out / "rust-unexports-macos.txt").read_text()


def map_locals(text: str) -> list[str]:
    body = text.split("local:", 1)[1].rsplit("};", 1)[0]
    return [l.strip().rstrip(";") for l in body.splitlines() if l.strip()]


class LayoutTest(unittest.TestCase):
    def test_shared_lists_are_gone(self):
        for name in ("rust-hidden.txt", "rust-exports.map", "rust-unexports-macos.txt"):
            self.assertFalse((CMAKE_DIR / name).exists(), f"libobs/cmake/{name} is generated now")

    def test_fragments_are_named_after_their_ffi_module(self):
        frags = sorted(FRAGMENTS.glob("*.txt"))
        self.assertTrue(frags, "libobs/cmake/rust-hidden.d/*.txt is missing")
        modules = {f"{p.parts[-4]}-{p.stem}" for p in (ROOT / "rust").glob("*/src/ffi/*.rs")}
        for frag in frags:
            self.assertIn(frag.stem, modules, f"{frag.name}: no rust/<crate>/src/ffi/<module>.rs")

    def test_fragments_hold_plain_unique_names(self):
        seen: dict[str, str] = {}
        for frag in sorted(FRAGMENTS.glob("*.txt")):
            names = entries(frag)
            self.assertTrue(names, f"{frag.name} is empty")
            for name in names:
                self.assertRegex(name, NAME, f"{frag.name}: wildcards and markers go in rust-hidden-base.txt")
                self.assertNotIn(name, seen, f"{name} in {frag.name} and {seen.get(name)}")
                seen[name] = frag.name

    def test_base_lines_are_names_or_patterns_with_an_optional_linker(self):
        for line in entries(BASE):
            self.assertRegex(line, r"^[A-Za-z0-9_*]+( (elf|macos))?$")


@unittest.skipUnless(shutil.which("cmake"), "cmake is not installed")
class GeneratorTest(unittest.TestCase):
    def test_generator_output_format_is_pinned(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            (tmp / "d").mkdir()
            (tmp / "d/obs-b-two.txt").write_text("# comment\nb_one\nb_two\n")
            (tmp / "d/obs-a-one.txt").write_text("a_one\n")
            (tmp / "base.txt").write_text("# head\n_ZN*\nrust_eh_personality\n__is*At macos\nelf_only elf\n")
            out = tmp / "out"
            got_map, got_macos = generate(out, tmp / "d", tmp / "base.txt")
            self.assertEqual(
                got_map,
                "/* Generated by libobs/cmake/rust-hidden.cmake from rust-hidden-base.txt\n"
                " * and rust-hidden.d/*.txt. Do not edit. */\n"
                "{\n  local:\n    _ZN*;\n    rust_eh_personality;\n    elf_only;\n"
                "    a_one;\n    b_one;\n    b_two;\n};\n",
            )
            self.assertEqual(
                got_macos,
                "# Generated by libobs/cmake/rust-hidden.cmake from rust-hidden-base.txt\n"
                "# and rust-hidden.d/*.txt. Do not edit.\n"
                "__ZN*\n_rust_eh_personality\n___is*At\n_a_one\n_b_one\n_b_two\n",
            )

    def test_repo_outputs_cover_base_and_every_fragment(self):
        names = [n for f in sorted(FRAGMENTS.glob("*.txt")) for n in entries(f)]
        base = [l.split() for l in entries(BASE)]
        with tempfile.TemporaryDirectory() as tmp:
            got_map, got_macos = generate(Path(tmp))
            self.assertEqual(map_locals(got_map), [b[0] for b in base if b[1:] != ["macos"]] + names)
            macos = [l for l in got_macos.splitlines() if l and not l.startswith("#")]
            self.assertEqual(macos, ["_" + b[0] for b in base if b[1:] != ["elf"]] + ["_" + n for n in names])

    def test_hevc_off_hides_the_hevc_shims(self):
        with tempfile.TemporaryDirectory() as tmp:
            got_map, got_macos = generate(Path(tmp), hevc=False)
            for name in HEVC:
                self.assertIn(f"    {name};\n", got_map)
                self.assertIn(f"_{name}\n", got_macos)


class ScopeTest(unittest.TestCase):
    def test_fragment_edit_selects_linux_only(self):
        got = scope(["libobs/cmake/rust-hidden.d/obs-core-video_plan.txt", "rust/obs-core/src/ffi/video_plan.rs"])
        self.assertTrue(got.core and got.tier2)
        self.assertFalse(got.macos or got.windows)

    def test_base_list_and_generator_stay_shared(self):
        for path in ("libobs/cmake/rust-hidden-base.txt", "libobs/cmake/rust-hidden.cmake"):
            got = scope([path])
            self.assertTrue(got.macos and got.windows, path)


if __name__ == "__main__":
    unittest.main()
